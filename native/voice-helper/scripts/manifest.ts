import { writeFile } from "node:fs/promises";
import { VOICE_PACKS } from "../../../apps/desktop/src/main/models/voice-manifest.ts";
import { resolveVoiceManifest } from "../../../apps/desktop/src/main/models/voice-manifest-builder.ts";

const packs = await resolveVoiceManifest(VOICE_PACKS);
for (const pack of packs) {
  process.stdout.write(`${pack.id}: ${pack.files.length} files, ${pack.files.reduce((n, f) => n + f.size, 0)} bytes\n`);
}
await writeFile(new URL("../../../apps/desktop/src/main/models/voice-packs.ts", import.meta.url),
  'import type { VoicePack } from "./voice-manifest.ts";\n// Generated by npm run voices:manifest. Review licenses and provenance before shipping.\n' +
  `export const VOICE_PACKS: VoicePack[] = ${JSON.stringify(packs, null, 2)};\n`);
